/* ===========================================================
 * Project storage — uses Puter KV + FS when signed in,
 * falls back to localStorage when guest.
 * Data shape:
 *   { id, title, description, tags, html, css, js, createdAt,
 *     updatedAt, published: { url, subdomain } | null }
 * =========================================================== */
(function (global) {
  'use strict';

  const KV_INDEX = 'nexus:projects:index';
  const KV_PREFIX = 'nexus:project:';
  const LS_KEY = 'nexus_projects_v1';

  function uid() {
    return 'p_' + Math.random().toString(36).slice(2, 9) + Date.now().toString(36).slice(-4);
  }

  function nowISO() { return new Date().toISOString(); }

  async function isCloud() {
    try { return await PuterBridge.isSignedIn(); } catch { return false; }
  }

  /* ---- local fallback ---- */
  function lsLoad() {
    try { return JSON.parse(localStorage.getItem(LS_KEY) || '[]'); } catch { return []; }
  }
  function lsSave(list) {
    localStorage.setItem(LS_KEY, JSON.stringify(list));
  }

  /* ---- list all projects ---- */
  async function listProjects() {
    if (await isCloud()) {
      const keys = await PuterBridge.kvList(KV_PREFIX);
      const out = [];
      for (const k of keys) {
        const key = typeof k === 'string' ? k : k.key;
        if (!key || !key.startsWith(KV_PREFIX)) continue;
        const proj = await PuterBridge.kvGet(key);
        if (proj) out.push(proj);
      }
      out.sort((a, b) => (b.updatedAt || '').localeCompare(a.updatedAt || ''));
      return out;
    } else {
      return lsLoad().sort((a, b) => (b.updatedAt || '').localeCompare(a.updatedAt || ''));
    }
  }

  async function getProject(id) {
    if (!id) return null;
    if (await isCloud()) {
      return await PuterBridge.kvGet(KV_PREFIX + id);
    }
    return lsLoad().find(p => p.id === id) || null;
  }

  async function saveProject(proj) {
    if (!proj.id) proj.id = uid();
    if (!proj.createdAt) proj.createdAt = nowISO();
    proj.updatedAt = nowISO();

    if (await isCloud()) {
      await PuterBridge.kvSet(KV_PREFIX + proj.id, proj);
    } else {
      const list = lsLoad();
      const i = list.findIndex(p => p.id === proj.id);
      if (i >= 0) list[i] = proj; else list.unshift(proj);
      lsSave(list);
    }
    return proj;
  }

  async function deleteProject(id) {
    if (await isCloud()) {
      await PuterBridge.kvDelete(KV_PREFIX + id);
    } else {
      lsSave(lsLoad().filter(p => p.id !== id));
    }
  }

  /* ---- Build a single self-contained HTML doc from a project ---- */
  function buildHtmlDoc(proj) {
    const title = (proj.title || 'NEXUS Project').replace(/</g, '&lt;');
    return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="description" content="${(proj.description || '').replace(/"/g, '&quot;')}">
<title>${title}</title>
<style>
${proj.css || ''}
</style>
</head>
<body>
${proj.html || ''}
<script>
${proj.js || ''}
<\/script>
</body>
</html>`;
  }

  /* ---- Export as ZIP (uses JSZip via CDN) ---- */
  async function exportZip(proj) {
    if (typeof JSZip === 'undefined') {
      await loadScript('https://cdn.jsdelivr.net/npm/jszip@3.10.1/dist/jszip.min.js');
    }
    const zip = new JSZip();
    zip.file('index.html', buildHtmlDoc({ ...proj, css: '', js: '' }).replace(
      '<style>\n\n</style>', `<link rel="stylesheet" href="styles.css">`
    ).replace(
      `<script>\n\n<\/script>`, `<script src="app.js"><\/script>`
    ));
    zip.file('styles.css', proj.css || '');
    zip.file('app.js', proj.js || '');
    zip.file('README.md', `# ${proj.title}\n\n${proj.description || ''}\n\nGenerated by NEXUS AI Builder.\n`);
    const blob = await zip.generateAsync({ type: 'blob' });
    triggerDownload(blob, (proj.title || 'project').replace(/\s+/g, '-').toLowerCase() + '.zip');
  }

  function loadScript(src) {
    return new Promise((res, rej) => {
      const s = document.createElement('script');
      s.src = src; s.onload = res; s.onerror = rej;
      document.head.appendChild(s);
    });
  }

  function triggerDownload(blob, filename) {
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = filename;
    document.body.appendChild(a); a.click(); a.remove();
    URL.revokeObjectURL(url);
  }

  /* ---- Publish project to Puter hosting ---- */
  async function publishProject(proj) {
    if (!await isCloud()) throw new Error('Sign in to publish');
    const slug = (proj.title || 'site').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 30) || 'site';
    const subdomain = `${slug}-${proj.id.slice(2, 8)}`.replace(/[^a-z0-9-]/g, '');
    const dir = `~/Public/nexus-sites/${proj.id}`;
    await PuterBridge.fsMkdir(dir);
    await PuterBridge.fsWrite(`${dir}/index.html`, buildHtmlDoc(proj));
    const site = await PuterBridge.publishSite(dir, subdomain);
    const url = site && (site.subdomain ? `https://${site.subdomain}.puter.site` : (site.url || ''));
    proj.published = { url, subdomain };
    await saveProject(proj);
    return proj.published;
  }

  global.ProjectStore = {
    listProjects, getProject, saveProject, deleteProject,
    buildHtmlDoc, exportZip, publishProject, uid,
  };
})(window);
